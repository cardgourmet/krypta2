export const getSVGForSymbol = (symbol: `{${string}}`) => {
  const code = symbol
    .toUpperCase()
    .substring(1)
    .substring(0, symbol.length - 2);

  return mtgSymbolSVG[code as keyof typeof mtgSymbolSVG] as unknown as
    | {
        blurDataURL: string;
        blurHeight: number;
        blurWidth: number;
        height: number;
        src: string;
        width: number;
      }
    | undefined;
};

export function MtgSymbolSVG({ symbol, size }: { symbol: `{${string}}`; size: number }) {
  const svg = getSVGForSymbol(symbol as `{${string}}`);

  return <>{svg && <Image src={svg} style={{ width: rem(size) }} />}</>;
}
